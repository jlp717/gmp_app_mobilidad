  IF EXISTS (
    SELECT 1 FROM (
      VALUES
      ('UX_T_RLO_TOKEN','TEST_REPARTIDOR_LIQUIDACION_OPS','YES','IDEMPOTENCY_TOKEN:A'),
      ('UX_T_RLO_MARKER','TEST_REPARTIDOR_LIQUIDACION_OPS','YES','IDMARCALIQUIDACION:A'),
