      ('IX_T_LIQ_GASTO_DAY','TEST_REPARTIDOR_LIQUIDACION_GASTOS','NO','CODIGO_REPARTIDOR:A,DIA:A,MES:A,ANO:A,STATUS:A'),
      ('IX_T_LIQ_AJUSTE_DAY','TEST_REPARTIDOR_LIQUIDACION_AJUSTES','NO','CODIGO_REPARTIDOR:A,DIA:A,MES:A,ANO:A,STATUS:A'),
      ('IX_T_LIQ_INGRESO_DAY','TEST_REPARTIDOR_LIQUIDACION_INGRESOS','NO','CODIGO_REPARTIDOR:A,DIA:A,MES:A,ANO:A,STATUS:A'),
      ('IX_T_LIQ_OUTBOX_STATUS','TEST_REPARTIDOR_LIQUIDACION_OUTBOX','NO','STATUS:A,CREATED_AT:A')
    ) AS E(INDEX_NAME,TABLE_NAME,IS_UNIQUE,KEYS)
    JOIN (
      SELECT I.INDEX_NAME,I.TABLE_NAME,CASE I.IS_UNIQUE WHEN 'U' THEN 'YES' WHEN 'D' THEN 'NO' ELSE I.IS_UNIQUE END AS IS_UNIQUE,
        LISTAGG(K.COLUMN_NAME || ':' || K.ORDERING,',') WITHIN GROUP (ORDER BY K.ORDINAL_POSITION) AS KEYS
      FROM QSYS2.SYSINDEXES I JOIN QSYS2.SYSKEYS K
        ON K.INDEX_SCHEMA=I.INDEX_SCHEMA AND K.INDEX_NAME=I.INDEX_NAME
      WHERE I.INDEX_SCHEMA='JAVIER'
      GROUP BY I.INDEX_NAME,I.TABLE_NAME,I.IS_UNIQUE
    ) AS A ON A.INDEX_NAME=E.INDEX_NAME
      WHERE A.TABLE_NAME<>E.TABLE_NAME OR A.IS_UNIQUE<>E.IS_UNIQUE OR A.KEYS<>E.KEYS
      FETCH FIRST 1 ROW ONLY
  ) THEN SIGNAL SQLSTATE '75012' SET MESSAGE_TEXT='STOP_TEST_INDEX_METADATA_MISMATCH'; END IF;
END@

