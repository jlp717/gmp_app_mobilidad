  UPDATED_BY VARCHAR(50),
  UPDATED_AT TIMESTAMP
);

ALTER TABLE JAVIER.REPARTIDOR_COMMISSION_TIERS ADD PRIMARY KEY (ID);

ALTER TABLE JAVIER.REPARTIDOR_COMMISSION_TIERS
  CHECK (ACTIVE_SN IN ('S', 'N'));

CREATE INDEX JAVIER.IDX_REP_COMM_ACTIVE
  ON JAVIER.REPARTIDOR_COMMISSION_TIERS (ACTIVE_SN, SORT_ORDER);

