   OR TRIM(PANTALLA_ORIGEN) = '';

UPDATE JAVIER.REPARTIDOR_COBROS
SET OPERADOR = 'legacy'
WHERE OPERADOR IS NULL
   OR TRIM(OPERADOR) = '';

