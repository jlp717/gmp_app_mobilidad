-- Repartidor finance suite schema.
-- Manual DB2 migration for DSN=GMP.
--
-- Important:
--   JAVIER.REPARTIDOR_COBROS already exists in 002_create_repartidor_tables.sql.
--   This migration extends that table instead of recreating it, so historical
--   delivery/payment data and the existing FK to REPARTIDOR_ENTREGAS survive.
--
-- DB2 for i ODBC compatibility:
--   - ADD CONSTRAINT fails with SQL5051 (qualifier mismatch bug).
--   - Use CREATE UNIQUE INDEX instead of UNIQUE constraints.
--   - Use ALTER TABLE ... CHECK (...) (unnamed) instead of CHECK constraints.
--   - ALTER COLUMN SET NOT NULL fails with HY008; rely on UNIQUE INDEX for
--     implicit NOT NULL enforcement.
--
-- Execution rule:
--   Run statements in order. If DB2 returns "column/object already exists"
--   for an ADD COLUMN, CREATE INDEX, CREATE TABLE, or ADD CONSTRAINT statement,
--   skip only that statement and continue with the next one.

-- ---------------------------------------------------------------------------
-- 1. Delivery status table used by Rutero confirmations
-- ---------------------------------------------------------------------------

CREATE TABLE JAVIER.DELIVERY_STATUS (
  ID VARCHAR(160) NOT NULL PRIMARY KEY,
  STATUS VARCHAR(20) DEFAULT 'PENDIENTE',
  OBSERVACIONES VARCHAR(512),
  FIRMA_PATH VARCHAR(255),
  LATITUD DECIMAL(10, 8),
  LONGITUD DECIMAL(11, 8),
  UPDATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
  REPARTIDOR_ID VARCHAR(20)
);

CREATE INDEX JAVIER.IDX_DELIVERY_STATUS_REP
  ON JAVIER.DELIVERY_STATUS (REPARTIDOR_ID, UPDATED_AT);

-- ---------------------------------------------------------------------------
-- 2. LQD shadow table for test mode.
--    Same physical structure as DSEDAC.LQD, but isolated in JAVIER.
--    Backend default: REPARTIDOR_FINANCE_ERP_SCHEMA=JAVIER.
--    Production cutover: set REPARTIDOR_FINANCE_ERP_SCHEMA=DSEDAC.
-- ---------------------------------------------------------------------------

CREATE TABLE JAVIER.LQD LIKE DSEDAC.LQD;

CREATE INDEX JAVIER.IDX_LQD_REP_TEST_NUMERO
  ON JAVIER.LQD (
    SUBEMPRESALIQUIDACION,
    EJERCICIOLIQUIDACION,
    SERIELIQUIDACION,
    TERMINALLIQUIDACION,
    NUMEROLIQUIDACION
  );

CREATE INDEX JAVIER.IDX_LQD_REP_TEST_IDMARCA
  ON JAVIER.LQD (IDMARCALIQUIDACION);

