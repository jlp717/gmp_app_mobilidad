  ON JAVIER.REPARTIDOR_COBROS (LIQUIDACION_TOKEN);

-- ---------------------------------------------------------------------------
-- 4. Pending balance carried to the next daily liquidation
-- ---------------------------------------------------------------------------

CREATE TABLE JAVIER.REPARTIDOR_FINANCIAL_BALANCES (
  CODIGO_REPARTIDOR VARCHAR(20) NOT NULL PRIMARY KEY,
  SALDO_PENDIENTE DECIMAL(15, 2) NOT NULL DEFAULT 0,
  UPDATED_BY VARCHAR(50) NOT NULL DEFAULT 'system',
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------------
-- 5. Local operation ledger for ERP LQD writes and idempotency
-- ---------------------------------------------------------------------------

CREATE TABLE JAVIER.REPARTIDOR_LIQUIDACION_OPS (
  ID BIGINT GENERATED ALWAYS AS IDENTITY,
  IDEMPOTENCY_TOKEN VARCHAR(128) NOT NULL,
  SUBEMPRESA_LIQ CHAR(3) NOT NULL DEFAULT 'GMP',
  EJERCICIO_LIQ INTEGER NOT NULL,
  SERIE_LIQ VARCHAR(5) NOT NULL DEFAULT 'A',
  TERMINAL_LIQ INTEGER NOT NULL,
  NUMERO_LIQ INTEGER NOT NULL,
  CODIGO_REPARTIDOR VARCHAR(20) NOT NULL,
  TOTAL_EFECTIVO DECIMAL(15, 2) NOT NULL DEFAULT 0,
  TOTAL_CHEQUES DECIMAL(15, 2) NOT NULL DEFAULT 0,
  TOTAL_TARJETA DECIMAL(15, 2) NOT NULL DEFAULT 0,
  TOTAL_POSTDATADOS DECIMAL(15, 2) NOT NULL DEFAULT 0,
  SALDO_ANTERIOR DECIMAL(15, 2) NOT NULL DEFAULT 0,
  TOTAL_COBROS_DIA DECIMAL(15, 2) NOT NULL DEFAULT 0,
  GASTOS DECIMAL(15, 2) NOT NULL DEFAULT 0,
  TOTAL_A_INGRESAR DECIMAL(15, 2) NOT NULL DEFAULT 0,
  INGRESO_BANCO DECIMAL(15, 2) NOT NULL DEFAULT 0,
  EFECTIVO_2 DECIMAL(15, 2) NOT NULL DEFAULT 0,
  ENTREGADO_2 DECIMAL(15, 2) NOT NULL DEFAULT 0,
  SALDO_RESULTANTE DECIMAL(15, 2) NOT NULL DEFAULT 0,
  PANTALLA_ORIGEN VARCHAR(20) NOT NULL DEFAULT 'LIQUIDACION_DIARIA',
  CREADO_POR VARCHAR(50) NOT NULL,
  STATUS VARCHAR(20) NOT NULL DEFAULT 'CLOSED',
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE JAVIER.REPARTIDOR_LIQUIDACION_OPS ADD PRIMARY KEY (ID);

CREATE UNIQUE INDEX JAVIER.UX_REP_LIQ_TOKEN
  ON JAVIER.REPARTIDOR_LIQUIDACION_OPS (IDEMPOTENCY_TOKEN);

CREATE UNIQUE INDEX JAVIER.UX_REP_LIQ_NUMERO
  ON JAVIER.REPARTIDOR_LIQUIDACION_OPS (
    SUBEMPRESA_LIQ,
    EJERCICIO_LIQ,
    SERIE_LIQ,
    TERMINAL_LIQ,
    NUMERO_LIQ
  );

ALTER TABLE JAVIER.REPARTIDOR_LIQUIDACION_OPS
  CHECK (STATUS IN ('CLOSED', 'VOID'));

CREATE INDEX JAVIER.IDX_REP_LIQ_REP_FECHA
  ON JAVIER.REPARTIDOR_LIQUIDACION_OPS (CODIGO_REPARTIDOR, CREATED_AT);

-- ---------------------------------------------------------------------------
-- 6. Email delivery log. Email failure never rolls back financial closing.
-- ---------------------------------------------------------------------------

CREATE TABLE JAVIER.REPARTIDOR_LIQUIDACION_EMAILS (
  ID BIGINT GENERATED ALWAYS AS IDENTITY,
  LIQUIDACION_OP_ID BIGINT NOT NULL,
  RECIPIENT_EMAIL VARCHAR(180) NOT NULL,
  EMAIL_KIND VARCHAR(20) NOT NULL,
  STATUS VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  ERROR_MESSAGE VARCHAR(1000),
  SENT_AT TIMESTAMP,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE JAVIER.REPARTIDOR_LIQUIDACION_EMAILS ADD PRIMARY KEY (ID);

ALTER TABLE JAVIER.REPARTIDOR_LIQUIDACION_EMAILS
  CHECK (EMAIL_KIND IN ('REPARTIDOR', 'INTERNO'));

ALTER TABLE JAVIER.REPARTIDOR_LIQUIDACION_EMAILS
  CHECK (STATUS IN ('PENDING', 'SENT', 'FAILED'));

CREATE INDEX JAVIER.IDX_REP_LIQ_EMAIL_OP
  ON JAVIER.REPARTIDOR_LIQUIDACION_EMAILS (LIQUIDACION_OP_ID, STATUS);

-- ---------------------------------------------------------------------------
-- 7. Editable commission tiers for repartidores
-- ---------------------------------------------------------------------------

