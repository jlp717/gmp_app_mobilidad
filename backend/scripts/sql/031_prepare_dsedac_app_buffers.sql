-- ==========================================================
-- 3) Difference summary: mapped JAVIER columns vs DSEDAC columns
-- ==========================================================
WITH COLUMN_MAP (SOURCE_TABLE, SOURCE_COLUMN, TARGET_TABLE, TARGET_COLUMN, FLOW) AS (
  VALUES
    ('PEDIDOS_CAB', 'CODIGOCLIENTE', 'CPC', 'CODIGOCLIENTEFACTURA', 'PEDIDOS_HEADER'),
    ('PEDIDOS_CAB', 'CODIGOVENDEDOR', 'CPC', 'CODIGOVENDEDOR', 'PEDIDOS_HEADER'),
    ('PEDIDOS_CAB', 'IMPORTETOTAL', 'CPC', 'IMPORTETOTAL', 'PEDIDOS_HEADER'),
    ('PEDIDOS_LIN', 'CODIGOARTICULO', 'LPC', 'CODIGOARTICULO', 'PEDIDOS_LINE'),
    ('PEDIDOS_LIN', 'CANTIDADENVASES', 'LPC', 'CANTIDADENVASES', 'PEDIDOS_LINE'),
    ('PEDIDOS_LIN', 'CANTIDADUNIDADES', 'LPC', 'CANTIDADUNIDADES', 'PEDIDOS_LINE'),
    ('PEDIDOS_LIN', 'PRECIOVENTA', 'LPC', 'PRECIOVENTA', 'PEDIDOS_LINE'),
    ('PEDIDOS_LIN', 'IMPORTEVENTA', 'LPC', 'IMPORTEVENTA', 'PEDIDOS_LINE'),
    ('COBROS', 'CODIGO_CLIENTE', 'CRC', 'CODIGOCLIENTEFACTURA', 'COBROS'),
    ('COBROS', 'CODIGO_USUARIO', 'CRC', 'CODIGOVENDEDOR', 'COBROS'),
    ('COBROS', 'IMPORTE', 'CRC', 'IMPORTECOBRADO', 'COBROS')
)
SELECT 'TYPE_DIFF_SUMMARY' AS CHECK_NAME,
       m.FLOW,
       'JAVIER.' CONCAT m.SOURCE_TABLE CONCAT '.' CONCAT m.SOURCE_COLUMN AS SOURCE_COLUMN,
       s.DATA_TYPE AS SOURCE_TYPE,
       s.LENGTH AS SOURCE_LENGTH,
       s.NUMERIC_SCALE AS SOURCE_SCALE,
       'DSEDAC.' CONCAT m.TARGET_TABLE CONCAT '.' CONCAT m.TARGET_COLUMN AS TARGET_COLUMN,
       d.DATA_TYPE AS TARGET_TYPE,
       d.LENGTH AS TARGET_LENGTH,
       d.NUMERIC_SCALE AS TARGET_SCALE,
       CASE
         WHEN s.COLUMN_NAME IS NULL THEN 'SOURCE_MISSING'
         WHEN d.COLUMN_NAME IS NULL THEN 'TARGET_MISSING'
         WHEN COALESCE(s.DATA_TYPE, '') <> COALESCE(d.DATA_TYPE, '')
           OR COALESCE(s.LENGTH, -1) <> COALESCE(d.LENGTH, -1)
           OR COALESCE(s.NUMERIC_SCALE, -1) <> COALESCE(d.NUMERIC_SCALE, -1)
           THEN 'TYPE_DIFF'
         ELSE 'OK'
       END AS STATUS
FROM COLUMN_MAP m
LEFT JOIN QSYS2.SYSCOLUMNS s
  ON s.TABLE_SCHEMA = 'JAVIER'
 AND s.TABLE_NAME = m.SOURCE_TABLE
 AND s.COLUMN_NAME = m.SOURCE_COLUMN
LEFT JOIN QSYS2.SYSCOLUMNS d
  ON d.TABLE_SCHEMA = 'DSEDAC'
 AND d.TABLE_NAME = m.TARGET_TABLE
 AND d.COLUMN_NAME = m.TARGET_COLUMN
ORDER BY m.FLOW, m.SOURCE_TABLE, m.SOURCE_COLUMN;

-- ==========================================================
-- 4) Non-destructive JAVIER repair: add *_NEW numeric columns if missing
--    Known safe pending issue: keep DSEDAC untouched; do not drop/rename originals.
