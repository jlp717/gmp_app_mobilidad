SELECT TABLE_SCHEMA, TABLE_NAME, TABLE_TYPE
FROM QSYS2.SYSTABLES
WHERE TABLE_SCHEMA = 'DSEDAC'
  AND TABLE_NAME IN (
    'PEDIDOS_CAB', 'PEDIDOS_LIN', 'PEDIDOS_SEQ', 'PEDIDOS_STOCK_RESERVE',
    'COBROS', 'REPARTIDOR_COBROS'
  )
ORDER BY TABLE_NAME@

SELECT s.TABLE_NAME,
       s.COLUMN_COUNT AS JAVIER_COLUMNS,
       t.COLUMN_COUNT AS DSEDAC_COLUMNS,
       s.IDENTITY_COLUMNS AS JAVIER_IDENTITY_COLUMNS,
       t.IDENTITY_COLUMNS AS DSEDAC_IDENTITY_COLUMNS,
       s.DEFAULT_COLUMNS AS JAVIER_DEFAULT_COLUMNS,
       t.DEFAULT_COLUMNS AS DSEDAC_DEFAULT_COLUMNS
FROM (
  SELECT TABLE_NAME,
         COUNT(*) AS COLUMN_COUNT,
         SUM(CASE WHEN IS_IDENTITY = 'YES' THEN 1 ELSE 0 END) AS IDENTITY_COLUMNS,
         SUM(CASE WHEN COLUMN_DEFAULT IS NOT NULL THEN 1 ELSE 0 END) AS DEFAULT_COLUMNS
  FROM QSYS2.SYSCOLUMNS
  WHERE TABLE_SCHEMA = 'JAVIER'
    AND TABLE_NAME IN ('PEDIDOS_CAB', 'PEDIDOS_LIN', 'PEDIDOS_SEQ', 'PEDIDOS_STOCK_RESERVE', 'COBROS', 'REPARTIDOR_COBROS')
  GROUP BY TABLE_NAME
) s
LEFT JOIN (
  SELECT TABLE_NAME,
         COUNT(*) AS COLUMN_COUNT,
         SUM(CASE WHEN IS_IDENTITY = 'YES' THEN 1 ELSE 0 END) AS IDENTITY_COLUMNS,
         SUM(CASE WHEN COLUMN_DEFAULT IS NOT NULL THEN 1 ELSE 0 END) AS DEFAULT_COLUMNS
  FROM QSYS2.SYSCOLUMNS
  WHERE TABLE_SCHEMA = 'DSEDAC'
    AND TABLE_NAME IN ('PEDIDOS_CAB', 'PEDIDOS_LIN', 'PEDIDOS_SEQ', 'PEDIDOS_STOCK_RESERVE', 'COBROS', 'REPARTIDOR_COBROS')
  GROUP BY TABLE_NAME
) t ON t.TABLE_NAME = s.TABLE_NAME
ORDER BY s.TABLE_NAME@

SELECT INDEX_SCHEMA, INDEX_NAME, TABLE_NAME, IS_UNIQUE, COLUMN_COUNT
FROM QSYS2.SYSINDEXES
WHERE INDEX_SCHEMA = 'DSEDAC'
  AND (INDEX_NAME LIKE 'IDX031_%' OR INDEX_NAME = 'UX031_REPCOB_TOK')
ORDER BY INDEX_NAME@

