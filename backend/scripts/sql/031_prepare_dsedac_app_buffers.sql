  VALUES
    ('DSEDAC', 'CPC', 'PEDIDOS_HEADER_TARGET'),
    ('DSEDAC', 'LPC', 'PEDIDOS_LINE_TARGET'),
    ('DSEDAC', 'CRC', 'COBROS_TARGET'),
    ('DSEDAC', 'CVC', 'COBROS_RELATED_TARGET'),
    ('JAVIER', 'PEDIDOS_CAB', 'PEDIDOS_HEADER_SOURCE'),
    ('JAVIER', 'PEDIDOS_LIN', 'PEDIDOS_LINE_SOURCE'),
    ('JAVIER', 'COBROS', 'COBROS_SOURCE')
)
SELECT 'PRECHECK_TABLES' AS CHECK_NAME,
       r.TABLE_SCHEMA,
       r.TABLE_NAME,
       r.FLOW,
       CASE WHEN t.TABLE_NAME IS NULL THEN 'MISSING' ELSE 'OK' END AS STATUS,
       t.TABLE_TYPE
FROM REQUIRED_TABLES r
LEFT JOIN QSYS2.SYSTABLES t
  ON t.TABLE_SCHEMA = r.TABLE_SCHEMA
 AND t.TABLE_NAME = r.TABLE_NAME
ORDER BY r.TABLE_SCHEMA, r.TABLE_NAME;

