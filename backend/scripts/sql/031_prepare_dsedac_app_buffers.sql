-- Purpose: sequential safe alignment for JAVIER test/write tables vs real DSEDAC ERP tables.
-- Scope: pedidos/cobros only. Default executable SQL must not mutate DSEDAC.
-- Run in IBM i ACS Run SQL Scripts against DSN GMP. Stop if any PRECHECK row is MISSING.
--
-- PILOTO profile:
--   DB2_READ_SCHEMA=DSEDAC
--   DB2_WRITE_SCHEMA=JAVIER
--   PEDIDOS_EXPORT_TO_SYSTEM=false
--
-- STAGING/PROD profile, until a separate export refactor changes this:
--   DB2_READ_SCHEMA=DSEDAC
--   DB2_WRITE_SCHEMA=JAVIER
--   PEDIDOS_EXPORT_TO_SYSTEM=true
--   PEDIDOS_DSEDAC_EXPORT_APPROVED=true
