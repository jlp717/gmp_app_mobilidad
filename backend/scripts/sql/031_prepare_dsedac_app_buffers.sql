-- ==========================================================
-- 5) PASS queries for the JAVIER repair
--    Expected PASS: NULLS_IN_NEW=0, DIFF_ROWS=0, OVER_LIMIT_ROWS=0.
-- ==========================================================
WITH CHECKS (COLUMN_NAME, NULLS_IN_NEW, DIFF_ROWS, OVER_LIMIT_ROWS) AS (
  SELECT 'IMPORTETOTAL_NEW',
         COALESCE(SUM(CASE WHEN IMPORTETOTAL_NEW IS NULL THEN 1 ELSE 0 END), 0),
         COALESCE(SUM(CASE
           WHEN ABS(COALESCE(IMPORTETOTAL, 0)) > 99999999.99 THEN 0
           WHEN DECIMAL(COALESCE(IMPORTETOTAL, 0), 10, 2) <> IMPORTETOTAL_NEW THEN 1
           ELSE 0
         END), 0),
         COALESCE(SUM(CASE WHEN ABS(COALESCE(IMPORTETOTAL, 0)) > 99999999.99 THEN 1 ELSE 0 END), 0)
  FROM JAVIER.PEDIDOS_CAB
  UNION ALL
  SELECT 'IMPORTECOSTO_NEW',
         COALESCE(SUM(CASE WHEN IMPORTECOSTO_NEW IS NULL THEN 1 ELSE 0 END), 0),
         COALESCE(SUM(CASE
           WHEN ABS(COALESCE(IMPORTECOSTO, 0)) > 99999999.99 THEN 0
           WHEN DECIMAL(COALESCE(IMPORTECOSTO, 0), 10, 2) <> IMPORTECOSTO_NEW THEN 1
           ELSE 0
         END), 0),
         COALESCE(SUM(CASE WHEN ABS(COALESCE(IMPORTECOSTO, 0)) > 99999999.99 THEN 1 ELSE 0 END), 0)
  FROM JAVIER.PEDIDOS_CAB
  UNION ALL
  SELECT 'IMPORTEMARGEN_NEW',
         COALESCE(SUM(CASE WHEN IMPORTEMARGEN_NEW IS NULL THEN 1 ELSE 0 END), 0),
         COALESCE(SUM(CASE
           WHEN ABS(COALESCE(IMPORTEMARGEN, 0)) > 99999999.99 THEN 0
           WHEN DECIMAL(COALESCE(IMPORTEMARGEN, 0), 10, 2) <> IMPORTEMARGEN_NEW THEN 1
           ELSE 0
         END), 0),
         COALESCE(SUM(CASE WHEN ABS(COALESCE(IMPORTEMARGEN, 0)) > 99999999.99 THEN 1 ELSE 0 END), 0)
  FROM JAVIER.PEDIDOS_CAB
)
SELECT 'JAVIER_REPAIR_PASS' AS CHECK_NAME,
       COLUMN_NAME,
       NULLS_IN_NEW,
       DIFF_ROWS,
       OVER_LIMIT_ROWS,
       CASE
         WHEN NULLS_IN_NEW = 0 AND DIFF_ROWS = 0 AND OVER_LIMIT_ROWS = 0 THEN 'PASS'
         ELSE 'BLOCK'
       END AS STATUS
FROM CHECKS
ORDER BY COLUMN_NAME;

WITH EXPECTED_REPAIR_COLUMNS (COLUMN_NAME) AS (
  VALUES
    ('IMPORTETOTAL_NEW'),
    ('IMPORTECOSTO_NEW'),
    ('IMPORTEMARGEN_NEW')
)
SELECT 'REPAIR_COLUMN_TYPE_PASS' AS CHECK_NAME,
       e.COLUMN_NAME,
       c.DATA_TYPE,
       c.LENGTH,
       c.NUMERIC_SCALE,
       CASE
         WHEN c.COLUMN_NAME IS NOT NULL
          AND c.DATA_TYPE IN ('DECIMAL', 'NUMERIC')
          AND c.LENGTH = 10
          AND c.NUMERIC_SCALE = 2
           THEN 'PASS'
         ELSE 'BLOCK'
       END AS STATUS
FROM EXPECTED_REPAIR_COLUMNS e
LEFT JOIN QSYS2.SYSCOLUMNS c
  ON c.TABLE_SCHEMA = 'JAVIER'
 AND c.TABLE_NAME = 'PEDIDOS_CAB'
 AND c.COLUMN_NAME = e.COLUMN_NAME
ORDER BY e.COLUMN_NAME;

