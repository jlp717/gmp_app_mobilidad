    ) THEN
    EXECUTE IMMEDIATE 'ALTER TABLE JAVIER.PEDIDOS_CAB ADD COLUMN IMPORTETOTAL_NEW NUMERIC(10,2)';
  END IF;

  IF EXISTS (
      SELECT 1 FROM QSYS2.SYSTABLES
      WHERE TABLE_SCHEMA = 'JAVIER' AND TABLE_NAME = 'PEDIDOS_CAB'
    )
    AND NOT EXISTS (
      SELECT 1 FROM QSYS2.SYSCOLUMNS
      WHERE TABLE_SCHEMA = 'JAVIER' AND TABLE_NAME = 'PEDIDOS_CAB'
        AND COLUMN_NAME = 'IMPORTECOSTO_NEW'
    ) THEN
    EXECUTE IMMEDIATE 'ALTER TABLE JAVIER.PEDIDOS_CAB ADD COLUMN IMPORTECOSTO_NEW NUMERIC(10,2)';
  END IF;

  IF EXISTS (
      SELECT 1 FROM QSYS2.SYSTABLES
      WHERE TABLE_SCHEMA = 'JAVIER' AND TABLE_NAME = 'PEDIDOS_CAB'
    )
    AND NOT EXISTS (
      SELECT 1 FROM QSYS2.SYSCOLUMNS
      WHERE TABLE_SCHEMA = 'JAVIER' AND TABLE_NAME = 'PEDIDOS_CAB'
        AND COLUMN_NAME = 'IMPORTEMARGEN_NEW'
    ) THEN
