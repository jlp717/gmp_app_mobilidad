-- 031_prepare_dsedac_app_buffers.sql
-- Purpose: prepare optional DSEDAC app-buffer tables for DB2_WRITE_SCHEMA=DSEDAC
-- Scope: copy app-buffer table structures from JAVIER only. No data copy. No DROP. No CPC/LPC/CRC mutation.
-- Verified source metadata on 2026-06-22 via QSYS2:
--   JAVIER.PEDIDOS_CAB: 176 columns, 1 identity, 36 defaults
--   JAVIER.PEDIDOS_LIN: 83 columns, 1 identity, 22 defaults
--   JAVIER.PEDIDOS_SEQ: 2 columns, 0 identity, 1 default
--   JAVIER.PEDIDOS_STOCK_RESERVE: 6 columns, 1 identity, 3 defaults
--   JAVIER.COBROS: 43 columns, 0 identity, 2 defaults
--   JAVIER.REPARTIDOR_COBROS: 130 columns, 1 identity, 108 defaults
--   JAVIER.BOLSA_COMERCIAL and JAVIER.MOVIMIENTOS_BOLSA exist, but current code writes them explicitly in JAVIER.
-- Note: CREATE TABLE ... LIKE does not copy indexes. Indexes needed by pedidos/cobros are created below.

--#SET TERMINATOR @

-- =============================
-- 0) PRECHECK: source/target tables
-- =============================
SELECT TABLE_SCHEMA, TABLE_NAME, TABLE_TYPE
FROM QSYS2.SYSTABLES
WHERE TABLE_SCHEMA IN ('JAVIER', 'DSEDAC')
  AND TABLE_NAME IN (
    'PEDIDOS_CAB', 'PEDIDOS_LIN', 'PEDIDOS_SEQ', 'PEDIDOS_STOCK_RESERVE',
    'PEDIDOS_IDEMPOTENCY', 'COBROS', 'REPARTIDOR_COBROS',
    'BOLSA_COMERCIAL', 'MOVIMIENTOS_BOLSA'
  )
ORDER BY TABLE_SCHEMA, TABLE_NAME@

-- PRECHECK: source structure summary. Expected rows: all except PEDIDOS_IDEMPOTENCY.
SELECT TABLE_NAME,
       COUNT(*) AS COLUMN_COUNT,
       SUM(CASE WHEN IS_IDENTITY = 'YES' THEN 1 ELSE 0 END) AS IDENTITY_COLUMNS,
       SUM(CASE WHEN COLUMN_DEFAULT IS NOT NULL THEN 1 ELSE 0 END) AS DEFAULT_COLUMNS
FROM QSYS2.SYSCOLUMNS
WHERE TABLE_SCHEMA = 'JAVIER'
  AND TABLE_NAME IN (
    'PEDIDOS_CAB', 'PEDIDOS_LIN', 'PEDIDOS_SEQ', 'PEDIDOS_STOCK_RESERVE',
    'COBROS', 'REPARTIDOR_COBROS', 'BOLSA_COMERCIAL', 'MOVIMIENTOS_BOLSA'
  )
GROUP BY TABLE_NAME
ORDER BY TABLE_NAME@

