--#SET TERMINATOR @
BEGIN
  IF EXISTS (
      SELECT 1 FROM QSYS2.SYSTABLES
      WHERE TABLE_SCHEMA = 'JAVIER' AND TABLE_NAME = 'PEDIDOS_CAB'
