-- TEST-only commercial settlement + return overlay.
-- NOT executed by startup. Never ALTER/CREATE DSEDAC. Never dump CVC/CPC/LQD.
-- Apply only after QSYS2.SYSTABLES says the object is missing:
--   node backend/scripts/ensure-comercial-test-ddl.js --apply
--
-- JAVIER.TEST_LIQUIDACION_COMERCIAL  -> persist Guardar liquidación
-- JAVIER.TEST_DEVOLUCIONES_COMERCIAL -> persist Devuelve (no LACLAE)

CREATE TABLE JAVIER.TEST_LIQUIDACION_COMERCIAL (
  ID INTEGER NOT NULL GENERATED ALWAYS AS IDENTITY,
  CODIGO_VENDEDOR CHAR(2) NOT NULL,
  FECHA DATE NOT NULL,
  INGRESO_BANCO DECIMAL(11, 2) NOT NULL DEFAULT 0,
  ENTREGADO DECIMAL(11, 2) NOT NULL DEFAULT 0,
  TOTAL_ESPERADO DECIMAL(11, 2) NOT NULL DEFAULT 0,
  TOTAL_EFECTIVO DECIMAL(11, 2) NOT NULL DEFAULT 0,
  TOTAL_CHEQUES DECIMAL(11, 2) NOT NULL DEFAULT 0,
  TOTAL_POSTDATADOS DECIMAL(11, 2) NOT NULL DEFAULT 0,
  SALDO_ACTUAL DECIMAL(11, 2) NOT NULL DEFAULT 0,
  DEVOLUCIONES_YA_COBRADAS DECIMAL(11, 2) NOT NULL DEFAULT 0,
  TOTAL_A_INGRESAR DECIMAL(11, 2) NOT NULL DEFAULT 0,
  STATUS VARCHAR(20) NOT NULL DEFAULT 'SAVED',
  IDEMPOTENCY_TOKEN VARCHAR(128) NOT NULL,
  CREATED_BY VARCHAR(20),
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  PRIMARY KEY (ID)
);

CREATE UNIQUE INDEX JAVIER.UX_TEST_LIQCOM_VENDOR_DAY
  ON JAVIER.TEST_LIQUIDACION_COMERCIAL (CODIGO_VENDEDOR, FECHA);

CREATE UNIQUE INDEX JAVIER.UX_TEST_LIQCOM_TOKEN
  ON JAVIER.TEST_LIQUIDACION_COMERCIAL (IDEMPOTENCY_TOKEN);

CREATE TABLE JAVIER.TEST_DEVOLUCIONES_COMERCIAL (
  ID INTEGER NOT NULL GENERATED ALWAYS AS IDENTITY,
  SERIE CHAR(4) NOT NULL,
  NUMERO INTEGER NOT NULL,
  CLIENTE CHAR(10) NOT NULL,
  VENDEDOR CHAR(2) NOT NULL,
  FECHA DATE NOT NULL,
  IMPORTE DECIMAL(11, 2) NOT NULL,
  UNIDADES DECIMAL(11, 3) NOT NULL DEFAULT 0,
  DOCUMENTO_ORIGEN VARCHAR(40),
  YA_COBRADA SMALLINT NOT NULL DEFAULT 1,
  IDEMPOTENCY_TOKEN VARCHAR(128) NOT NULL,
  CREATED_BY VARCHAR(20),
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  PRIMARY KEY (ID)
);

CREATE UNIQUE INDEX JAVIER.UX_TEST_DEVCOM_TOKEN
  ON JAVIER.TEST_DEVOLUCIONES_COMERCIAL (IDEMPOTENCY_TOKEN);

CREATE UNIQUE INDEX JAVIER.UX_TEST_DEVCOM_DOC
  ON JAVIER.TEST_DEVOLUCIONES_COMERCIAL (VENDEDOR, FECHA, SERIE, NUMERO, CLIENTE);
