-- Additive proposal for the isolated TEST order state audit ledger.
-- Target is fixed to JAVIER.TEST_PEDIDO_STATE_EVENTS. Never run against
-- DSEDAC, DSED, or a non-isolated table set.
--
-- This file is intentionally applied only by
-- scripts/tools/ensure-pedido-state-events-test-ddl.js --apply, whose default
-- mode is read-free dry-run and whose mutation path requires APP_ENV=test,
-- REPARTO_TABLE_SET=isolated_test and ALLOW_DB2_DDL=true.

CREATE TABLE JAVIER.TEST_PEDIDO_STATE_EVENTS (
  ID BIGINT GENERATED ALWAYS AS IDENTITY NOT NULL,
  PEDIDO_ID INTEGER NOT NULL,
  FROM_STATE VARCHAR(24),
  TO_STATE VARCHAR(24) NOT NULL,
  ACTOR_ID VARCHAR(80) NOT NULL,
  ACTOR_ROLE VARCHAR(32),
  DEVICE_ID VARCHAR(128),
  REASON VARCHAR(500),
  IDEMPOTENCY_KEY VARCHAR(128) NOT NULL,
  PAYLOAD_JSON CLOB(262144) NOT NULL,
  PAYLOAD_HASH CHAR(64) NOT NULL,
  ORIGINAL_CLIENT_AT TIMESTAMP,
  SERVER_OCCURRED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT PK_TEST_PED_STATE_EVENTS PRIMARY KEY (ID),
  CONSTRAINT UQ_TEST_PED_STATE_EVT_IDEMP UNIQUE (IDEMPOTENCY_KEY),
  CONSTRAINT CK_TEST_PED_STATE_FROM CHECK (
    FROM_STATE IS NULL OR FROM_STATE IN (
      'BORRADOR', 'CONFIRMANDO', 'CONFIRMADO', 'CANCELANDO', 'CANCELADO'
    )
  ),
  CONSTRAINT CK_TEST_PED_STATE_TO CHECK (
    TO_STATE IN (
      'BORRADOR', 'CONFIRMANDO', 'CONFIRMADO', 'CANCELANDO', 'CANCELADO'
    )
  ),
  CONSTRAINT CK_TEST_PED_STATE_INITIAL CHECK (
    FROM_STATE IS NOT NULL OR TO_STATE = 'BORRADOR'
  ),
  CONSTRAINT CK_TEST_PED_STATE_CANCEL_REASON CHECK (
    TO_STATE <> 'CANCELADO' OR LENGTH(TRIM(COALESCE(REASON, ''))) > 0
  )
);

CREATE INDEX JAVIER.IX_TEST_PED_STATE_EVENT_ORDER
  ON JAVIER.TEST_PEDIDO_STATE_EVENTS (PEDIDO_ID, SERVER_OCCURRED_AT);

