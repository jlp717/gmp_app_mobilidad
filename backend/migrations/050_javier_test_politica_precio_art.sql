-- Additive TEST-only snapshot of the product pricing-policy evidence.
-- This file is reviewed/applied separately. The seed CLI never runs DDL.
-- Source reads: DSEDAC.ART and informational DSEDAC.ARA tariff 2.
-- Mutation target: JAVIER.TEST_POLITICA_PRECIO_ART only.

SET CURRENT SCHEMA JAVIER;

CREATE TABLE JAVIER.TEST_POLITICA_PRECIO_ART (
  CODIGOARTICULO CHAR(10) NOT NULL,
  DESCRIPCIONARTICULO CHAR(40) NOT NULL,
  UNIDAD_ERP CHAR(10) NOT NULL,
  UNIDADES_CAJA DECIMAL(10, 5) NOT NULL,
  ANO_BAJA DECIMAL(4, 0) NOT NULL,
  ACTIVO_SN CHAR(1) NOT NULL,
  TARIFA_CANDIDATA_CODIGO DECIMAL(2, 0),
  PRECIO_CANDIDATO DECIMAL(9, 4),
  TARIFA_VARIANTES INTEGER NOT NULL,
  TARIFA_ESTADO VARCHAR(24) NOT NULL,
  UNIDAD_ESTADO VARCHAR(24) NOT NULL,
  POLITICA_ESTADO VARCHAR(32) NOT NULL,
  COSTE_FABRICACION DECIMAL(11, 4),
  MARGEN_OBJETIVO_PCT DECIMAL(7, 4),
  PRECIO_MINIMO DECIMAL(11, 4),
  SOURCE_FINGERPRINT CHAR(64) NOT NULL,
  SOURCE_SNAPSHOT_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT PK_TEST_POLITICA_PRECIO_ART PRIMARY KEY (CODIGOARTICULO),
  CONSTRAINT CK_TEST_PPA_ACTIVO CHECK (ACTIVO_SN IN ('S', 'N')),
  CONSTRAINT CK_TEST_PPA_TARIFA_STATE CHECK (
    TARIFA_ESTADO IN ('AUSENTE', 'PRESENTE', 'ALTERNATIVA', 'CONFLICTIVA')
  ),
  CONSTRAINT CK_TEST_PPA_TARIFA_CANDIDATE CHECK (
    (TARIFA_ESTADO IN ('PRESENTE', 'ALTERNATIVA')
      AND TARIFA_CANDIDATA_CODIGO IS NOT NULL
      AND PRECIO_CANDIDATO IS NOT NULL
      AND TARIFA_VARIANTES = 1)
    OR
    (TARIFA_ESTADO = 'AUSENTE'
      AND TARIFA_CANDIDATA_CODIGO IS NULL
      AND PRECIO_CANDIDATO IS NULL
      AND TARIFA_VARIANTES = 0)
    OR
    (TARIFA_ESTADO = 'CONFLICTIVA'
      AND TARIFA_CANDIDATA_CODIGO IS NULL
      AND PRECIO_CANDIDATO IS NULL
      AND TARIFA_VARIANTES >= 2)
  ),
  CONSTRAINT CK_TEST_PPA_UNIDAD_STATE CHECK (
    UNIDAD_ESTADO IN ('NO_VERIFICADA', 'VERIFICADA', 'CONFLICTIVA')
  ),
  CONSTRAINT CK_TEST_PPA_POLICY_STATE CHECK (
    POLITICA_ESTADO IN (
      'SIN_EVIDENCIA', 'ALTERNATIVA_NO_EFECTIVA',
      'CONFLICTIVA', 'UOM_NO_VERIFICADA', 'VERIFICADA'
    )
  ),
  CONSTRAINT CK_TEST_PPA_MARGIN CHECK (
    MARGEN_OBJETIVO_PCT IS NULL
    OR (MARGEN_OBJETIVO_PCT >= 0 AND MARGEN_OBJETIVO_PCT < 100)
  ),
  CONSTRAINT CK_TEST_PPA_UNPROVEN CHECK (
    UNIDAD_ESTADO = 'VERIFICADA'
    OR (COSTE_FABRICACION IS NULL
        AND MARGEN_OBJETIVO_PCT IS NULL
        AND PRECIO_MINIMO IS NULL)
  )
);
