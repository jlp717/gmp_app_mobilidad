-- Reviewed additive TEST/DEMO migration; NEVER run from application startup.
-- Prerequisite: 050 exists with its original 19 columns and all owned data preserved.
-- Apply separately only after QSYS2 preflight verifies the exact starting schema.
-- Before enabling API writes, verify both physical files are journaled to
-- JAVIER/QSQJRN with *BOTH images (QSYS2.OBJECT_STATISTICS). This script does
-- not start/change journaling or modify any DSEDAC/DSED object.
SET CURRENT SCHEMA JAVIER;

ALTER TABLE JAVIER.TEST_POLITICA_PRECIO_ART ADD COLUMN UNIDAD_POLITICA VARCHAR(12);
ALTER TABLE JAVIER.TEST_POLITICA_PRECIO_ART ADD COLUMN MINIMO_ORIGEN VARCHAR(12) NOT NULL DEFAULT 'ERP_BASE';
ALTER TABLE JAVIER.TEST_POLITICA_PRECIO_ART ADD COLUMN POLITICA_REVISION INTEGER NOT NULL DEFAULT 0;
ALTER TABLE JAVIER.TEST_POLITICA_PRECIO_ART ADD COLUMN POLITICA_UPDATED_BY VARCHAR(40);
ALTER TABLE JAVIER.TEST_POLITICA_PRECIO_ART ADD COLUMN POLITICA_UPDATED_AT TIMESTAMP;
ALTER TABLE JAVIER.TEST_POLITICA_PRECIO_ART DROP CONSTRAINT CK_TEST_PPA_UNPROVEN;
ALTER TABLE JAVIER.TEST_POLITICA_PRECIO_ART ADD CONSTRAINT CK_TEST_PPA_OWNED_PAIR CHECK (
  (COSTE_FABRICACION IS NULL AND MARGEN_OBJETIVO_PCT IS NULL)
  OR (COSTE_FABRICACION IS NOT NULL AND MARGEN_OBJETIVO_PCT IS NOT NULL
      AND COSTE_FABRICACION >= 0 AND MARGEN_OBJETIVO_PCT >= 0 AND MARGEN_OBJETIVO_PCT < 100)
);
ALTER TABLE JAVIER.TEST_POLITICA_PRECIO_ART ADD CONSTRAINT CK_TEST_PPA_MIN_ORIGIN CHECK (MINIMO_ORIGEN IN ('ERP_BASE','MANUAL'));
ALTER TABLE JAVIER.TEST_POLITICA_PRECIO_ART ADD CONSTRAINT CK_TEST_PPA_OWNED_MIN CHECK (PRECIO_MINIMO IS NULL OR PRECIO_MINIMO >= 0);
ALTER TABLE JAVIER.TEST_POLITICA_PRECIO_ART ADD CONSTRAINT CK_TEST_PPA_OWNED_UNIT CHECK (UNIDAD_POLITICA IS NULL OR UNIDAD_POLITICA IN ('CAJAS','KILO','UNIDADES'));
ALTER TABLE JAVIER.TEST_POLITICA_PRECIO_ART ADD CONSTRAINT CK_TEST_PPA_REVISION CHECK (POLITICA_REVISION >= 0);

CREATE TABLE JAVIER.TEST_POLITICA_PRECIO_ART_AUDIT (
  ID INTEGER GENERATED ALWAYS AS IDENTITY NOT NULL PRIMARY KEY,
  CODIGOARTICULO CHAR(10) NOT NULL,
  ACTION VARCHAR(24) NOT NULL,
  REVISION_PREVIA INTEGER NOT NULL,
  POLITICA_REVISION INTEGER NOT NULL,
  UNIDAD_PREVIA VARCHAR(12), UNIDAD_NUEVA VARCHAR(12),
  COSTE_PREVIO DECIMAL(11,4), COSTE_NUEVO DECIMAL(11,4),
  MARGEN_PREVIO DECIMAL(7,4), MARGEN_NUEVO DECIMAL(7,4),
  MINIMO_PREVIO DECIMAL(11,4), MINIMO_NUEVO DECIMAL(11,4),
  ORIGEN_PREVIO VARCHAR(12) NOT NULL, ORIGEN_NUEVO VARCHAR(12) NOT NULL,
  UNIDAD_ESTADO_PREVIO VARCHAR(24) NOT NULL, UNIDAD_ESTADO_NUEVO VARCHAR(24) NOT NULL,
  POLITICA_ESTADO_PREVIO VARCHAR(32) NOT NULL, POLITICA_ESTADO_NUEVO VARCHAR(32) NOT NULL,
  SOURCE_PREVIO CHAR(64) NOT NULL, SOURCE_NUEVO CHAR(64) NOT NULL,
  ACTOR_CODE VARCHAR(40) NOT NULL, ACTOR_ROLE VARCHAR(24) NOT NULL,
  REASON VARCHAR(250) NOT NULL, REQUEST_KEY VARCHAR(96) NOT NULL, PAYLOAD_HASH CHAR(64) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT UQ_TEST_PPA_AUDIT_REQUEST UNIQUE (REQUEST_KEY),
  CONSTRAINT CK_TEST_PPA_AUDIT_ACTION CHECK (ACTION IN ('CREATE','UPDATE','UOM_CONFLICT','REFRESH')),
  CONSTRAINT CK_TEST_PPA_AUDIT_REV CHECK (REVISION_PREVIA >= 0 AND POLITICA_REVISION >= REVISION_PREVIA),
  CONSTRAINT CK_TEST_PPA_AUDIT_ROLE CHECK (ACTOR_ROLE IN ('ADMIN','JEFE_VENTAS','SYSTEM_REFRESH'))
);
CREATE INDEX JAVIER.IX_TEST_PPA_AUDIT_ART_AT ON JAVIER.TEST_POLITICA_PRECIO_ART_AUDIT (CODIGOARTICULO, CREATED_AT);
